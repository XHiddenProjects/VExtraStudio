/* Vextra Studio – "Export website": packs the whole project into a ZIP or tar.gz together with ready-to-use .htaccess and nginx.conf,
 * an optional copy of the project database, and short deployment notes. */
(function () {
  const { h } = VX;
  const S = VX.app.S;
  const Web = VX.web;
  const enc = new TextEncoder();

  const SKIP = /(^|\/)(node_modules|\.git|\.svn|\.hg|__MACOSX)(\/|$)|(^|\/)(\.DS_Store|Thumbs\.db)$|^database\.sqlite$/i;

  Web.serverConfigs = function ({ name = 'mysite', domain = 'example.com', php = false, spa = false, has404 = false } = {}) {
    const htaccess = `# Generated by Vextra Studio – Apache configuration (needs AllowOverride All for this folder).
Options -Indexes
DirectoryIndex ${php ? 'index.php ' : ''}index.html

<IfModule mod_rewrite.c>
  RewriteEngine On
  # Force HTTPS in production: remove the leading # on the next three lines.
  # RewriteCond %{HTTPS} off
  # RewriteCond %{HTTP_HOST} !^localhost
  # RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [L,R=301]
${spa ? `  # Single-page app: send unknown URLs to index.html
  RewriteCond %{REQUEST_FILENAME} !-f
  RewriteCond %{REQUEST_FILENAME} !-d
  RewriteRule ^ /index.html [L]` : `  # Single-page app? Uncomment to send unknown URLs to index.html:
  # RewriteCond %{REQUEST_FILENAME} !-f
  # RewriteCond %{REQUEST_FILENAME} !-d
  # RewriteRule ^ /index.html [L]`}
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/plain text/css text/javascript application/javascript application/json application/xml image/svg+xml
</IfModule>

<IfModule mod_expires.c>
  ExpiresActive On
  ExpiresByType text/html "access plus 0 seconds"
  ExpiresByType text/css "access plus 1 week"
  ExpiresByType application/javascript "access plus 1 week"
  ExpiresByType text/javascript "access plus 1 week"
  ExpiresByType image/png "access plus 1 month"
  ExpiresByType image/jpeg "access plus 1 month"
  ExpiresByType image/webp "access plus 1 month"
  ExpiresByType image/svg+xml "access plus 1 month"
  ExpiresByType font/woff2 "access plus 1 year"
</IfModule>

<IfModule mod_headers.c>
  Header always set X-Content-Type-Options "nosniff"
  Header always set X-Frame-Options "SAMEORIGIN"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
</IfModule>

# Never serve databases, dumps, logs or environment files.
<FilesMatch "\\.(sqlite|sqlite3|db|sql|env|log|bak|ini)$">
  <IfModule mod_authz_core.c>
    Require all denied
  </IfModule>
  <IfModule !mod_authz_core.c>
    Order allow,deny
    Deny from all
  </IfModule>
</FilesMatch>
${has404 ? '\nErrorDocument 404 /404.html\n' : ''}`;

    const nginx = `# Generated by Vextra Studio – nginx configuration.
# Save as /etc/nginx/conf.d/${name}.conf (or sites-available), upload the site to /var/www/${name}, then: nginx -t && systemctl reload nginx
server {
    listen 80;
    listen [::]:80;
    server_name ${domain} www.${domain};
    root /var/www/${name};
    index ${php ? 'index.php ' : ''}index.html;
    charset utf-8;

    # Redirect to HTTPS once you have a certificate (e.g. via certbot):
    # return 301 https://$host$request_uri;

    gzip on;
    gzip_comp_level 5;
    gzip_types text/plain text/css text/javascript application/javascript application/json application/xml image/svg+xml;

    add_header X-Content-Type-Options "nosniff" always;
    add_header X-Frame-Options "SAMEORIGIN" always;
    add_header Referrer-Policy "strict-origin-when-cross-origin" always;

    location / {
        ${php ? 'try_files $uri $uri/ /index.php?$query_string;' : spa ? 'try_files $uri $uri/ /index.html;' : 'try_files $uri $uri/ =404;'}
    }

    location ~* \\.(?:css|js|png|jpe?g|gif|webp|svg|ico|woff2?)$ {
        expires 30d;
        access_log off;
        add_header Cache-Control "public";
    }

    # Never serve hidden files, databases, dumps, logs or the db/ folder.
    location ~ /\\.(?!well-known) { deny all; }
    location ~* \\.(sqlite|sqlite3|db|sql|env|log|bak|ini)$ { deny all; }
    location ^~ /db/ { deny all; }
${has404 ? '\n    error_page 404 /404.html;\n' : ''}
${php ? `    # PHP via php-fpm (adjust the socket for your PHP version, e.g. /run/php/php8.3-fpm.sock)
    location ~ \\.php$ {
        include snippets/fastcgi-php.conf;
        fastcgi_pass unix:/run/php/php-fpm.sock;
    }` : `    # This site has no PHP files. To add PHP, uncomment:
    # location ~ \\.php$ {
    #     include snippets/fastcgi-php.conf;
    #     fastcgi_pass unix:/run/php/php-fpm.sock;
    # }`}
}
`;
    return { htaccess, nginx };
  };

  const readme = ({ name, php, db, format }) => `${name} – deployment notes (generated by Vextra Studio)
=====================================================================

1. Upload / unpack
   ${format === 'zip' ? `unzip ${name}.zip -d /var/www/` : `tar xzf ${name}.tar.gz -C /var/www/`}
   The site's files are in the "${name}/" folder – that folder is your web root.

2. Web server
   - Apache: the included .htaccess works as-is (enable mod_rewrite, mod_headers, mod_expires, mod_deflate and AllowOverride All).
   - nginx:  copy nginx.conf to /etc/nginx/conf.d/${name}.conf, edit server_name, then: nginx -t && systemctl reload nginx
${php ? `
3. PHP
   This site contains PHP files. Install PHP (and php-fpm for nginx) plus the SQLite extension:  apt install php php-fpm php-sqlite3
` : `
3. PHP
   Not used by this site.
`}${db ? `
4. Database
${db.sqlite ? '   db/database.sqlite  – the SQLite database from Vextra Studio. Make the db/ folder AND the file writable by the web server user, e.g.:\n     chown -R www-data:www-data db && chmod 750 db && chmod 660 db/database.sqlite\n' : ''}${db.sql ? '   db/database.sql     – a plain SQL dump. Restore it with:  sqlite3 db/database.sqlite < db/database.sql   (or import it into MySQL / PostgreSQL after adjusting types)\n' : ''}   The db/ folder is blocked from the web by both server configurations. Keep it that way.
` : ''}
Security checklist: serve over HTTPS, keep the db/ folder private, never commit secrets, and review any PHP before uploading it.
`;

  async function collect(opts) {
    const root = S.root; const rels = (await window.native.listFiles(root, 20000)).filter((r) => !SKIP.test(r));
    const entries = [];
    for (const rel of rels) {
      const open = VX.tabs.list().find((t) => t.path && VX.path.norm(t.path) === VX.path.norm(VX.path.join(root, rel)) && t.kind === 'code' && t.dirty);
      const data = open ? enc.encode(VX.tabs.kinds.code.text(open)) : VX.archive.fromB64(await window.native.readBase64(VX.path.join(root, rel)));
      entries.push({ path: rel, data });
    }
    return { rels, entries };
  }

  Web.buildSiteArchive = async function (opts) {
    const { name, format, domain, configs, dbMode } = opts; const { rels, entries } = await collect(opts);
    const has = (f) => rels.some((r) => r.toLowerCase() === f);
    const php = rels.some((r) => /\.(php|phtml|php\d)$/i.test(r)); const has404 = has('404.html');
    const spa = false; const notes = [];
    if (configs) {
      const c = Web.serverConfigs({ name, domain, php, spa, has404 });
      if (!has('.htaccess')) entries.push({ path: '.htaccess', data: c.htaccess }); else notes.push('.htaccess already in your project – kept as is');
      if (!has('nginx.conf')) entries.push({ path: 'nginx.conf', data: c.nginx }); else notes.push('nginx.conf already in your project – kept as is');
    }
    const db = { sqlite: false, sql: false };
    if (dbMode !== 'none') {
      const cur = VX.db && (await VX.db.open().catch(() => null));
      if (cur) {
        const tables = await VX.db.tables();
        if (tables.length || dbMode) {
          if (dbMode === 'sql' || dbMode === 'both') { entries.push({ path: 'db/database.sql', data: await VX.db.dump() }); db.sql = true; }
          if (dbMode === 'sqlite' || dbMode === 'both') { entries.push({ path: 'db/database.sqlite', data: await VX.db.exportBytes() }); db.sqlite = true; }
          if (db.sql || db.sqlite) entries.push({ path: 'db/.htaccess', data: '# The database must never be downloadable.\n<IfModule mod_authz_core.c>\n  Require all denied\n</IfModule>\n<IfModule !mod_authz_core.c>\n  Order allow,deny\n  Deny from all\n</IfModule>\n' });
        }
      }
    }
    if (opts.readme) entries.push({ path: 'README-DEPLOY.txt', data: readme({ name, php, db: db.sql || db.sqlite ? db : null, format }) });
    // everything goes into <name>/ so extracting never spills files into the current folder; the .htaccess/nginx.conf/README stay inside it too
    const wrapped = entries.map((e) => ({ ...e, path: name + '/' + e.path })).sort((a, b) => a.path.localeCompare(b.path));
    const bytes = format === 'zip' ? await VX.archive.zip(wrapped) : await VX.archive.tarGz(wrapped);
    return { bytes, count: entries.length, php, db, notes };
  };

  Web.exportSite = async function () {
    if (!S.root) { VX.ui.toast('Open a project folder first.', 'warn'); return VX.app.openFolder && VX.app.openFolder(); }
    const stem = VX.path.base(S.root).replace(/[^\w.-]+/g, '-').replace(/^-+|-+$/g, '') || 'website';
    const name = h('input', { value: stem }), domain = h('input', { value: 'example.com', placeholder: 'your-domain.com' });
    const fmt = h('select', {}, h('option', { value: 'zip' }, 'ZIP (.zip) – works everywhere'), h('option', { value: 'tgz' }, 'tar.gz (.tar.gz) – Linux / servers'));
    if (!VX.archive.hasGzip()) fmt.querySelector('[value=tgz]').disabled = true;
    const cfg = h('input', { type: 'checkbox', checked: true }), rd = h('input', { type: 'checkbox', checked: true });
    const dbSel = h('select', {}, h('option', { value: 'none' }, 'Do not include'), h('option', { value: 'sql' }, 'SQL dump (db/database.sql)'), h('option', { value: 'sqlite' }, 'SQLite file (db/database.sqlite)'), h('option', { value: 'both' }, 'Both'));
    try { const t = await VX.db.tables(); if (t.length) dbSel.value = 'sql'; } catch { /* engine missing */ }
    const row = (l, el, hint) => h('div', { class: 'xs-row' }, h('label', {}, l), el, hint ? h('small', {}, hint) : null);
    const body = h('div', { class: 'xs' }, row('Site folder name', name, 'The archive contains one folder with this name.'), row('Format', fmt), row('Domain (for nginx.conf)', domain),
      h('div', { class: 'xs-row' }, h('label', {}, h('span', {}, cfg, ' Include '), h('b', {}, '.htaccess'), ' and ', h('b', {}, 'nginx.conf'))), h('div', { class: 'xs-row' }, h('label', {}, rd, ' Include README-DEPLOY.txt')),
      row('Database', dbSel, 'Stored in db/ and blocked from the web by both configs.'),
      h('div', { class: 'ask-hint' }, 'node_modules, .git, hidden folders and the local database.sqlite are never included. Unsaved editor changes are included.'));
    return new Promise((resolve) => {
      const btn = h('button', { class: 'btn primary' }, '📦 Export');
      const m = VX.ui.modal({ title: 'Export website', size: 'small', body, onClose: () => resolve(null), actions: [btn] });
      btn.onclick = async () => {
        const nm = name.value.trim().replace(/[^\w.-]+/g, '-') || stem; btn.disabled = true; btn.textContent = 'Packing…';
        try {
          const format = fmt.value === 'tgz' ? 'tgz' : 'zip';
          const r = await Web.buildSiteArchive({ name: nm, format, domain: domain.value.trim() || 'example.com', configs: cfg.checked, dbMode: dbSel.value, readme: rd.checked });
          const file = nm + (format === 'zip' ? '.zip' : '.tar.gz'); const saved = await window.native.saveBinary(file, VX.archive.toB64(r.bytes));
          m.close(); if (saved) VX.ui.toast(`Exported ${r.count} files → ${saved}${r.php ? ' (includes PHP)' : ''}`);
          resolve(r);
        } catch (e) { btn.disabled = false; btn.textContent = '📦 Export'; VX.ui.toast('Export failed: ' + e.message, 'error'); }
      };
    });
  };

  /* ------------------------------------------------------------ PHP preview (desktop app: runs `php -S`) */
  Web.openPhp = async function (src) {
    if (!S.root) return VX.ui.toast('Open a project folder first.', 'warn');
    try {
      const info = await window.native.php.start(S.root);
      const rel = src && src.path ? VX.path.rel(S.root, src.path) : '';
      const url = info.url + (/\.php$/i.test(rel) || /\.html?$/i.test(rel) ? rel : ''); VX.bottom && VX.bottom.log('info', `PHP server (${info.version}) running at ${info.url}`, 'php');
      const frame = h('iframe', { class: 'pv-frame', src: url, style: 'width:100%;height:100%;border:0;background:#fff' });
      const bar = h('div', { class: 'pv-bar' }, h('button', { class: 'btn sm', title: 'Reload', onclick: () => { frame.src = frame.src; } }, VX.icon('refresh', 14)), h('span', { class: 'tag' }, url), h('span', { class: 'spacer' }), h('button', { class: 'btn sm', onclick: () => window.open(url, '_blank') }, 'Open in browser'), h('button', { class: 'btn sm', onclick: async () => { await window.native.php.stop(S.root); VX.ui.toast('PHP server stopped'); } }, 'Stop server'));
      return VX.tabs.open({ kind: 'preview', key: 'php:' + S.root, title: 'PHP: ' + (rel || 'site'), icon: 'play', container: h('div', { class: 'pv', style: 'display:flex;flex-direction:column;height:100%' }, bar, frame), refresh() { frame.src = frame.src; }, onClose() { window.native.php.stop(S.root).catch(() => {}); } });
    } catch (e) { VX.ui.toast(e.message || String(e), 'error'); }
  };
})();
